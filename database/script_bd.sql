CREATE TABLE FORUM_SERVICE_DB.CATEGORIES (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255 CHAR)
);

CREATE TABLE FORUM_SERVICE_DB.POSTS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(200 CHAR) NOT NULL,
    CONTENT VARCHAR2(2000 CHAR) NOT NULL,
    AUTHOR_USERNAME VARCHAR2(60 CHAR) NOT NULL,
    BANNED NUMBER(1,0) DEFAULT 0 NOT NULL CHECK (BANNED IN (0, 1)),
    CATEGORY_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_POST_CATEGORY FOREIGN KEY (CATEGORY_ID)
        REFERENCES FORUM_SERVICE_DB.CATEGORIES(ID)
);

CREATE TABLE FORUM_SERVICE_DB.COMMENTS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONTENT VARCHAR2(1000 CHAR) NOT NULL,
    AUTHOR_USERNAME VARCHAR2(60 CHAR) NOT NULL,
    BANNED NUMBER(1,0) DEFAULT 0 NOT NULL CHECK (BANNED IN (0, 1)),
    POST_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_COMMENT_POST FOREIGN KEY (POST_ID)
        REFERENCES FORUM_SERVICE_DB.POSTS(ID) ON DELETE CASCADE
);

